"""
Εργασία 2 - Άσκηση 3
Πρωτεύον:
    min z = 32x2 + 50x3 - 19x5
    (P1) 15x1 + 15x2 + 15x3 + x5 = 40      -> y1 ελεύθερη
    (P2) 12x1 - 90x2 + 14x4      >= 18     -> y2 >= 0
    (P3)                     x4  <= 11     -> y3 <= 0
         xj >= 0

Δυϊκό (max), ένας περιορισμός ανά πρωτεύουσα μεταβλητή, όλοι <= :
    max W = 40y1 + 18y2 + 11y3
    (x1) 15y1 + 12y2       <= 0
    (x2) 15y1 - 90y2       <= 32
    (x3) 15y1              <= 50
    (x4)        14y2 + y3  <= 0
    (x5)  y1               <= -19

(α) επίλυση δυϊκού με PuLP/CBC + γεωμετρική περιγραφή της κορυφής
(β) εύρεση της συμπληρωματικής λύσης του πρωτεύοντος ΜΟΝΟ από τη δυϊκή
    θεωρία (complementary slackness) - χωρίς να λυθεί το πρωτεύον.
"""
import pulp

# =====================================================================
# (α) ΔΥΪΚΟ
# =====================================================================
dual = pulp.LpProblem("dyiko", pulp.LpMaximize)
y1 = pulp.LpVariable("y1", lowBound=None, upBound=None)   # ελεύθερη
y2 = pulp.LpVariable("y2", lowBound=0)                    # >= 0
y3 = pulp.LpVariable("y3", upBound=0)                     # <= 0
dual += 40 * y1 + 18 * y2 + 11 * y3, "W"
dual += 15 * y1 + 12 * y2 <= 0, "D_x1"
dual += 15 * y1 - 90 * y2 <= 32, "D_x2"
dual += 15 * y1 <= 50, "D_x3"
dual += 14 * y2 + y3 <= 0, "D_x4"
dual += y1 <= -19, "D_x5"
dual.solve(pulp.PULP_CBC_CMD(msg=0))

Y = {"y1": y1.value(), "y2": y2.value(), "y3": y3.value()}
print("=== (α) ΔΥΪΚΟ ===")
print(f" κατάσταση: {pulp.LpStatus[dual.status]}")
print(f" y* = ({Y['y1']}, {Y['y2']}, {Y['y3']}),   W* = {pulp.value(dual.objective)}")

DUALC = {"x1": (15 * Y["y1"] + 12 * Y["y2"], 0),
         "x2": (15 * Y["y1"] - 90 * Y["y2"], 32),
         "x3": (15 * Y["y1"], 50),
         "x4": (14 * Y["y2"] + Y["y3"], 0),
         "x5": (Y["y1"], -19)}
print("\n Δεσμευτικότητα δυϊκών περιορισμών:")
for kk, (lhs, rhs) in DUALC.items():
    st = "ΔΕΣΜΕΥΤΙΚΟΣ" if abs(lhs - rhs) < 1e-9 else "μη δεσμευτικός"
    print(f"   ({kk})  LHS = {lhs:>8.2f}   RHS = {rhs:>6}   περίσσεια = "
          f"{rhs-lhs:>8.2f}   {st}")
print("\n Ενεργά υπερεπίπεδα στον R^3 στο σημείο y* = (-19, 0, 0):")
print("   (x5): y1 = -19 ;  (x4): 14y2 + y3 = 0 ;  όριο y2 >= 0 ;  όριο y3 <= 0")
print("   -> 4 ενεργά υπερεπίπεδα ενώ αρκούν 3  =>  Η ΔΥΪΚΗ ΚΟΡΥΦΗ ΕΙΝΑΙ ΕΚΦΥΛΙΣΜΕΝΗ")

# απόδειξη μοναδικότητας του δυϊκού βέλτιστου (αλγεβρικά):
print("\n Μοναδικότητα: από (x5) y1 <= -19  =>  40y1 <= -760.")
print("   Από (x1) 12y2 <= -15y1 και από (x4) y3 <= -14y2, άρα")
print("   W = 40y1 + 18y2 + 11y3 <= 40y1 + 18y2 - 154y2 = 40y1 - 136y2 <= -760,")
print("   με ισότητα μόνο για y1 = -19, y2 = 0, y3 = 0. Άρα το δυϊκό βέλτιστο είναι ΜΟΝΑΔΙΚΟ.")

# =====================================================================
# (β) ΣΥΜΠΛΗΡΩΜΑΤΙΚΗ ΧΑΛΑΡΟΤΗΤΑ -> ΛΥΣΗ ΠΡΩΤΕΥΟΝΤΟΣ
# =====================================================================
print("\n=== (β) ΣΥΜΠΛΗΡΩΜΑΤΙΚΗ ΧΑΛΑΡΟΤΗΤΑ ===")
print(" CS-1: δυϊκός περιορισμός j ΜΗ δεσμευτικός  =>  x_j = 0")
zero = [kk for kk, (l, r) in DUALC.items() if abs(l - r) > 1e-9]
print(f"        μη δεσμευτικοί: {zero}  =>  " + ", ".join(f"{v}=0" for v in zero))
print(" CS-2: y_i != 0  =>  ο πρωτεύων περιορισμός i είναι δεσμευτικός")
print("        y1 = -19 != 0 -> ο P1 δεσμευτικός (ισχύει ούτως ή άλλως, είναι ισότητα)")
print("        y2 = 0, y3 = 0 -> δεν δίνουν πληροφορία για P2, P3")
print("\n Αντικατάσταση x1 = x2 = x3 = 0 στον P1:  15*0 + x5 = 40  =>  x5 = 40")
print(" Ο P2 απαιτεί 14 x4 >= 18  =>  x4 >= 9/7 ≈ 1.2857")
print(" Ο P3 απαιτεί x4 <= 11")
print(" Η αντικειμενική ΔΕΝ περιέχει x4 (c4 = 0)  =>  κάθε x4 στο [9/7, 11] είναι βέλτιστο.")
z = 32 * 0 + 50 * 0 - 19 * 40
print(f"\n z* = -19 * 40 = {z}  =  W*  ->  ισχυρή δυϊκότητα ✓")
print(" Το σύνολο των βέλτιστων λύσεων του πρωτεύοντος είναι η ΑΚΜΗ")
print("   { (0,0,0,x4,40) : 9/7 <= x4 <= 11 }")
print(" με ΚΟΡΥΦΕΣ (βασικές λύσεις):")
print("   x = (0,0,0, 9/7, 40)  (δεσμευτικός ο P2)")
print("   x = (0,0,0,  11, 40)  (δεσμευτικός ο P3)")

# ------------------------------------------------ ανεξάρτητη επαλήθευση
prim = pulp.LpProblem("prwteuon", pulp.LpMinimize)
X = [pulp.LpVariable(f"x{i+1}", lowBound=0) for i in range(5)]
prim += 32 * X[1] + 50 * X[2] - 19 * X[4]
prim += 15 * X[0] + 15 * X[1] + 15 * X[2] + X[4] == 40, "P1"
prim += 12 * X[0] - 90 * X[1] + 14 * X[3] >= 18, "P2"
prim += X[3] <= 11, "P3"
prim.solve(pulp.PULP_CBC_CMD(msg=0))
print(f"\n [επαλήθευση PuLP] πρωτεύον: x = {[v.value() for v in X]}, "
      f"z = {pulp.value(prim.objective)}")
print(" [επαλήθευση] και οι δύο κορυφές δίνουν z = -760:")
for x4 in (9/7, 11):
    print(f"   x4 = {x4:.4f}: P2 = {14*x4:.3f} >= 18 ->"
          f" {'OK' if 14*x4 >= 18-1e-9 else 'ΟΧΙ'},  z = {-19*40}")
